import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {parseEvidence} from '../../rea-local/dist/domain/evidence.js';
import {parseEvidenceBundle} from '../../rea-local/dist/domain/evidenceBundle.js';
import {toolContract} from '../../rea-local/dist/contracts/toolContracts.js';
const directory=path.dirname(fileURLToPath(import.meta.url));
const record=parseEvidence(JSON.parse(await fs.readFile(path.join(directory,'healthy-mcp/evaluator-instructions.evidence.json'),'utf8')));
toolContract('read_function_instructions').outputSchema.parse(record);
assert.equal(record.subject.digest.sha256,'6056139d78d9be98d2da8e64b2e7aab7c2946a130df392fa19af39a77963d578');
assert.equal(record.analysis_profile.provider.id,'ghidra');
assert.equal(record.analysis_profile.parameters.analysis_timeout_seconds,1);
assert.equal(record.analysis_profile.parameters.analysis_seeds.entries.function,1);
assert.ok(record.limitations.some(x=>x.includes('analysis_complete=false; analysis_timed_out=true')));
const result=record.normalized_result;
assert.equal(result.procedure.address,'0x1012fa3a0');
assert.equal(result.instructions.length,89);
assert.equal(result.procedure.body.total_bytes,356);
assert.equal(result.procedure.body.non_contiguous,true);
assert.equal(result.procedure.body.ranges.length,2);
assert.ok(result.instructions.some(x=>x.startsWith('0x1012fa3a0:')));
assert.ok(result.instructions.some(x=>x.startsWith('0x1005576fc:')));
const summary=JSON.parse(await fs.readFile(path.join(directory,'healthy-mcp/summary.json'),'utf8'));
assert.equal(summary.status,'completed');assert.equal(summary.calls,4);assert.equal(summary.errors,0);
assert.equal(summary.verifier_run.process_lineage.status,'verified');
assert.deepEqual(summary.verifier_run.process_lineage.descendants,[]);
const bundle=parseEvidenceBundle(JSON.parse(await fs.readFile(path.join(directory,'healthy-mcp/evidence-bundle.json'),'utf8')));
assert.ok(bundle.records.some(x=>x.evidence_id===record.evidence_id));
const receipt={status:'passed',checked_at:new Date().toISOString(),authority:'Fresh real Ghidra healthy-path observation; not a new ENOSPC event or a full Arc analysis',target_executed:false,evidence_id:record.evidence_id,profile_digest:record.analysis_profile.digest,analysis_timeout_seconds:1,analysis_complete:false,caller_function_seeds:1,instructions:result.instructions.length,body_bytes:result.procedure.body.total_bytes,ranges:result.procedure.body.ranges,bundle_records:bundle.records.length,successful_calls:summary.successful,cleanup:summary.verifier_run};
await fs.writeFile(path.join(directory,'healthy-verification.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({status:receipt.status,instructions:receipt.instructions,body_bytes:receipt.body_bytes,successful_calls:receipt.successful_calls}));
